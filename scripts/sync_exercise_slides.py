#!/usr/bin/env python3
"""Rebuild the closing «Задачи к лекции» slide of every introduction lecture.

The slide lists the titles of the main problems of the lecture, taken from the
shared problem file introduction/_includes/exercises/NN_*-{ru,en}.qmd, and links
to the problem page. The block between the two markers is generated; edit the
problem files and run

    python3 scripts/sync_exercise_slides.py          # rewrite the slides
    python3 scripts/sync_exercise_slides.py --check  # exit 1 if a slide is stale
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INTRO = ROOT / "introduction"
BEGIN = "<!-- exercises:begin (generated by scripts/sync_exercise_slides.py) -->"
END = "<!-- exercises:end -->"
# slide stem -> problem-file stem where the two differ
PROBLEM_STEM = {"09_vacuum_two_flavors": "09_vacuum_oscillations"}
TEXT = {
    "ru": dict(heading="Задачи к лекции", pattern=r"^## Задача (\d+\.\d+)\.\s+(.*)$",
               link="Все задачи к лекции {n} →", all="Все задачи курса",
               seminar="и задачи для разбора на семинаре"),
    "en": dict(heading="Problems for this lecture", pattern=r"^## Problem (\d+\.\d+)\.\s+(.*)$",
               link="All problems for lecture {n} →", all="All course problems",
               seminar="and problems for the seminar"),
}


def block(lang: str, number: str, page: str, problems: Path) -> str:
    t = TEXT[lang]
    text = problems.read_text(encoding="utf-8")
    titles = re.findall(t["pattern"], text, flags=re.M)
    if not titles:
        raise SystemExit(f"{problems}: no problem headings")
    seminar = "### Семинар" in text or "### Seminar" in text
    items = [f"- **{k}.** {title}" for k, title in titles]
    out = [BEGIN, "", f"## {t['heading']} {{#lecture-exercises}}", ""]
    if len(items) > 6:  # two columns keep up to ten titles inside the frame
        half = (len(items) + 1) // 2
        out += ['::: {.nh-text size="md"}', ":::: {.columns}"]
        for group in (items[:half], items[half:]):
            out += ['::: {.column width="50%"}', "", *group, "", ":::"]
        out += ["::::", ":::"]
    else:
        out += items
    tail = f" {t['seminar']}" if seminar else ""
    out += ["", '::: {.nh-box tone="question"}',
            f"[{t['link'].format(n=number)}](../exercises/{page}){tail} · "
            f"[{t['all']}](../exercises/index.qmd)",
            ":::", "", END]
    return "\n".join(out) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for lang in ("ru", "en"):
        for slide in sorted((INTRO / lang / "slides").glob("[0-9][0-9]_*.qmd")):
            stem = PROBLEM_STEM.get(slide.stem, slide.stem)
            problems = INTRO / "_includes/exercises" / f"{stem}-{lang}.qmd"
            page = f"{stem}_exercises.qmd"
            if not problems.exists() or not (INTRO / lang / "exercises" / page).exists():
                continue
            src = slide.read_text(encoding="utf-8")
            new_block = block(lang, slide.stem[:2], page, problems)
            if BEGIN in src:
                head, rest = src.split(BEGIN, 1)
                tail = rest.split(END, 1)[1]
                new = head + new_block.rstrip("\n") + tail
            else:
                new = src.rstrip("\n") + "\n\n" + new_block
            if new != src:
                stale.append(slide.relative_to(ROOT))
                if not check:
                    slide.write_text(new, encoding="utf-8")
    for path in stale:
        print(("stale: " if check else "updated: ") + str(path))
    return 1 if check and stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
