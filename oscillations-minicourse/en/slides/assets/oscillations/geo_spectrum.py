"""Inverse-beta-decay event spectrum of geoneutrinos for the scales applet.

Input: the antineutrino spectra of the 238U and 232Th chains by S. Enomoto
(https://www.awa.tohoku.ac.jp/~sanshiro/research/geoneutrino/spectrum/, 1 keV steps,
normalised to one decay of the head of the chain), downloaded to a local folder.
Cross section: zeroth order of Vogel & Beacom (1999), sigma ~ E_e p_e with E_e = E - 1.293 MeV.
The U and Th event spectra are scaled to the signals expected at JUNO, 30.3 and 9.0 TNU
(JUNO Yellow Book, J. Phys. G 43, 030401 (2016), Sec. 8).

Run:  python geo_spectrum.py <folder with AntineutrinoSpectrum_238U.knt and _232Th.knt>
Output: ../widgets/geo_ibd_spectrum.js (window.GEO_IBD_SPECTRUM, 25 keV bins from 1.8 to 3.3 MeV)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "widgets" / "geo_ibd_spectrum.js"
DELTA, ME = 1.29333, 0.51099895      # MeV: neutron-proton mass difference, electron mass
SIGNAL_TNU = {"238U": 30.3, "232Th": 9.0}
EDGES = np.round(np.arange(1.800, 3.3001, 0.025), 3)   # MeV


def chain(folder: Path, name: str) -> tuple[np.ndarray, np.ndarray]:
    data = np.loadtxt(folder / f"AntineutrinoSpectrum_{name}.knt", comments="#")
    return data[:, 0] / 1000.0, data[:, 1]           # MeV, 1/keV per decay


def ibd_events(E: np.ndarray, flux: np.ndarray) -> np.ndarray:
    Ee = E - DELTA
    pe = np.sqrt(np.clip(Ee ** 2 - ME ** 2, 0, None))
    return np.where(Ee > ME, flux * Ee * pe, 0.0)


def main(folder: Path) -> None:
    centres = 0.5 * (EDGES[1:] + EDGES[:-1])
    spectra = {}
    for name, tnu in SIGNAL_TNU.items():
        E, flux = chain(folder, name)
        ev = ibd_events(E, flux)
        binned = np.array([ev[(E >= lo) & (E < hi)].sum() for lo, hi in zip(EDGES[:-1], EDGES[1:])])
        spectra[name] = binned / binned.sum() * tnu
    total = spectra["238U"] + spectra["232Th"]
    norm = total.sum()
    payload = {"source": "S. Enomoto, U and Th chain spectra; IBD cross section of Vogel and Beacom (1999), zeroth order; "
                         "U:Th = 30.3:9.0 TNU (JUNO Yellow Book)",
               "E": [round(float(e), 4) for e in centres],
               "U": [round(float(v / norm), 6) for v in spectra["238U"]],
               "Th": [round(float(v / norm), 6) for v in spectra["232Th"]]}
    OUT.write_text("// Generated by assets/oscillations/geo_spectrum.py; do not edit.\n"
                   f"window.GEO_IBD_SPECTRUM = {json.dumps(payload)};\n", encoding="utf-8")
    print("wrote", OUT, "bins", len(centres), "U share", round(float(spectra['238U'].sum() / norm), 3))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
